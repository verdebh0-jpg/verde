export type Helpers = {
  t: (key: string) => string;
  l: (pair: readonly [string, string]) => string;
  p: (ar?: string | null, en?: string | null) => string;
};

export function makeHelpers(locale: Locale): Helpers {
  const i = locale === "ar" ? 0 : 1;
  return {
    t: (key) => D[key]?.[i] ?? key,
    l: (pair) => pair[i],
    p: (ar, en) => (locale === "ar" ? ar || en || "" : en || ar || ""),
  };
}
